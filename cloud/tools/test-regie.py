# La Régie EXIT pilotant le prototype EXIT Cloud (vrai OBS + vrai flux SRT)
import asyncio,os,base64
from playwright.async_api import async_playwright
ok=lambda c,m:print(('✅ ' if c else '❌ ')+m)
async def main():
  async with async_playwright() as p:
    b=await p.chromium.launch();c=await b.new_context(**p.devices['iPhone 15 Pro'])
    await c.add_init_script("localStorage.setItem('regie-obs-v2',JSON.stringify({host:'ws://127.0.0.1:4455',pass:'testexit',manual:true,pvFps:1}))")
    pg=await c.new_page();e=[];pg.on('pageerror',lambda x:e.append(str(x)))
    await pg.goto('file:///home/claude/regie-obs-exit/dev/tests/index.html');await pg.wait_for_timeout(9000)
    ok(await pg.evaluate("S.ok"),'La Régie se connecte au serveur EXIT')
    sc=await pg.evaluate("S.scenes");ok(all(s in sc for s in ['Ingest','Ingest Low-bitrate','Ingest Offline']),'Scènes : '+', '.join(sc))
    k=await pg.evaluate("S.ing&&S.ing.kbps");ok(k and k>2000,f'Débit LiveU affiché depuis l’agent : {k} kb/s ({await pg.evaluate("S.ing&&S.ing.name")})')
    ok(await pg.evaluate("entrySource()")=='Ingest Player','Caméra reconnue : Ingest Player')
    ok(await pg.evaluate("S.streaming"),'Voyant LIVE (sortie OBS active)')
    await pg.wait_for_timeout(4000)
    ok(await pg.evaluate("!!document.getElementById('pvImg').src"),'Aperçu image reçu')
    await pg.click('nav button[data-v=lut]');await pg.wait_for_timeout(600)
    await pg.click('#lutAdd');await pg.wait_for_timeout(500)
    if await pg.locator('[data-pack]').count(): await pg.click('[data-pack="0"]');await pg.wait_for_timeout(4000)
    else: await pg.click('#dClose');await pg.wait_for_timeout(400)
    ok(await pg.evaluate("LUT.list.length")==11,f'11 LUT installés sur la caméra ({await pg.evaluate("LUT.list.length")})')
    await pg.click('#v-lut .lut:has-text("Exterieur 02")');await pg.wait_for_timeout(1500)
    on=await pg.evaluate("(async()=>(await req('GetSourceFilterList',{sourceName:'Ingest Player'})).filters.filter(f=>f.filterEnabled).map(f=>f.filterName))()")
    ok(on==['LUT · Exterieur 02'],'Un seul LUT actif : '+', '.join(on))
    img=await pg.evaluate("(async()=>(await req('GetSourceScreenshot',{sourceName:'Ingest',imageFormat:'jpg',imageWidth:480},15000)).imageData)()")
    open('/tmp/claude-0/t/cloud-lut.jpg','wb').write(base64.b64decode(img.split(',')[1]))
    await pg.click('#v-lut .lut.none');await pg.wait_for_timeout(1500)
    img=await pg.evaluate("(async()=>(await req('GetSourceScreenshot',{sourceName:'Ingest',imageFormat:'jpg',imageWidth:480},15000)).imageData)()")
    open('/tmp/claude-0/t/cloud-nolut.jpg','wb').write(base64.b64decode(img.split(',')[1]))
    await pg.click('nav button[data-v=regie]');await pg.wait_for_timeout(500)
    await pg.screenshot(path='/tmp/claude-0/t/cloud-regie.png')
    ok(not e,'Aucune erreur '+str(e[:1]))
    await b.close()
asyncio.run(main())
