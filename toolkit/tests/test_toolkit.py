# EXIT Toolkit — tests de l'interface en mode démo
import asyncio,os
from playwright.async_api import async_playwright
ok=lambda c,m:print(('✅ ' if c else '❌ ')+m)
URL='file://'+os.path.abspath(os.path.join(os.path.dirname(__file__),'..','index.html'))
SHOT='/tmp/claude-0/t/tk'
async def main():
  os.makedirs(SHOT,exist_ok=True)
  async with async_playwright() as p:
    b=await p.chromium.launch();c=await b.new_context(viewport={'width':1440,'height':860},device_scale_factor=1)
    pg=await c.new_page();e=[];pg.on('pageerror',lambda x:e.append(str(x)))
    await pg.goto(URL);await pg.wait_for_timeout(400)
    ok(await pg.is_visible('#lp'),'Écran de connexion')
    await pg.fill('#lp','faux');await pg.click('button[type=submit]');ok('incorrect' in await pg.inner_text('#le'),'Mauvais mot de passe refusé')
    await pg.fill('#lp','exit');await pg.click('button[type=submit]');await pg.wait_for_timeout(800)
    nav=await pg.inner_text('.nav');ok(all(x in nav for x in ['Dashboard','OBS','Réglages']),'Menu : Dashboard / OBS / Réglages')
    ok(await pg.is_visible('[data-pw]'),'Serveur éteint → bouton Allumer')
    ok(await pg.locator('#dStream.dis').count()==1,'Actions grisées serveur éteint')
    await pg.screenshot(path=SHOT+'/01-eteint.png')
    await pg.click('[data-pw]');await pg.wait_for_timeout(2500)
    ok('Démarrage' in await pg.inner_text('#dPow'),'Démarrage avec étapes')
    await pg.screenshot(path=SHOT+'/02-demarrage.png')
    await pg.wait_for_timeout(5500)
    ok(await pg.evaluate("API.state.server")=='on','Serveur prêt')
    ok(await pg.is_disabled('#tOff')==False,'Éteindre dispo hors live')
    await pg.click('#dGo');await pg.wait_for_timeout(1500)
    ok(await pg.evaluate("API.state.streaming"),'Démarrer le stream')
    ok(await pg.is_disabled('#tOff'),'Éteindre grisé pendant le live')
    await pg.evaluate("API.power(false).catch(e=>window.__err=e.message)");await pg.wait_for_timeout(200)
    ok(await pg.evaluate("API.state.server")=='on' and 'live' in (await pg.evaluate("window.__err||''")),'Extinction refusée pendant un live (même forcée)')
    await pg.click('[data-sc="BACKUP MC"]');await pg.wait_for_timeout(1300)
    ok(await pg.evaluate("API.state.program")=='BACKUP MC','Changer de scène')
    await pg.wait_for_timeout(1500);await pg.screenshot(path=SHOT+'/03-live.png')
    await pg.click('#dStop');await pg.wait_for_timeout(300)
    ok(await pg.is_visible('#dlg'),'Arrêter le stream demande une confirmation')
    await pg.click('#dlgNo');await pg.wait_for_timeout(300);ok(await pg.evaluate("API.state.streaming"),'Annuler → le live continue')
    await pg.click('#dStop');await pg.wait_for_timeout(300);await pg.click('#dlgOk');await pg.wait_for_timeout(500)
    ok(not await pg.evaluate("API.state.streaming"),'Confirmer → stream arrêté')
    # pages
    for r,t,f in [('ingests','Ingests','04-ingests'),('destinations','Destinations','05-destinations'),('systeme','Système','06-systeme'),('video','Vidéo','07-video'),('acces','Accès','08-acces'),('obs/remote','OBS à distance','09-remote'),('obs/fichiers','Fichiers','10-fichiers'),('obs/collections','Collections','11-collections')]:
      await pg.evaluate(f"go('{r}')");await pg.wait_for_timeout(700)
      ok(t in await pg.inner_text('main h1'),'Page '+t);await pg.screenshot(path=SHOT+f'/{f}.png',full_page=True)
    await pg.evaluate("go('ingests')");await pg.wait_for_timeout(400)
    ok(await pg.get_attribute('#u1','type')=='password','Clés masquées par défaut')
    await pg.click('[data-show=u1]');ok(await pg.get_attribute('#u1','type')=='text','« Afficher » révèle la clé')
    await pg.evaluate("go('destinations')");await pg.wait_for_timeout(400)
    await pg.click('[data-new=twitch]');await pg.fill('#nN','test_chaine');await pg.fill('#nK','live_test');await pg.click('#nf button[type=submit]');await pg.wait_for_timeout(400)
    ok('test_chaine' in await pg.inner_text('main'),'Ajouter une destination Twitch')
    n0=await pg.locator('.dst').count();await pg.locator('[data-del]').last.click();await pg.click('#dlgOk');await pg.wait_for_timeout(300)
    ok(await pg.locator('.dst').count()==n0-1,'Supprimer une destination (avec confirmation)')
    await pg.evaluate("go('obs/fichiers')");await pg.wait_for_timeout(500)
    f0=await pg.locator('#fT tbody tr').count();await pg.locator('[data-rm]').first.click();await pg.click('#dlgOk');await pg.wait_for_timeout(500)
    ok(await pg.locator('#fT tbody tr').count()==f0-1,'Supprimer un fichier (avec confirmation)')
    await pg.hover('[data-menu=set] button');await pg.wait_for_timeout(300);await pg.screenshot(path=SHOT+'/12-menu.png')
    await pg.set_viewport_size({'width':1280,'height':760});await pg.evaluate("go('dashboard')");await pg.wait_for_timeout(1500);await pg.screenshot(path=SHOT+'/13-portable.png')
    ok(await pg.evaluate("document.documentElement.scrollWidth<=innerWidth"),'Pas de débordement horizontal (portable)')
    ok(not e,'Aucune erreur '+str(e[:2]))
    await b.close()
asyncio.run(main())
